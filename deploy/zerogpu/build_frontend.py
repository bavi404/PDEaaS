#!/usr/bin/env python3
"""Build the EXISTING Next.js frontend as a static export for the ZeroGPU Space (docs/ZEROGPU.md §3).

The source in frontend/ is not modified. The build runs on a temporary copy with two deploy-time differences:
  1. src/app/api/ (the Next.js proxy route) is removed. On the Space the browser's same-origin /api/* requests are
     served directly by FastAPI, so no proxy is needed. Static export cannot contain route handlers.
  2. next.config.ts sets output: "export" (instead of "standalone") and keeps the other options.

    python deploy/zerogpu/build_frontend.py                 # -> deploy/zerogpu/web
    python deploy/zerogpu/build_frontend.py --out DIR [--npm-ci]

Writes DIR/build-info.json (git commit, frontend tree hash, Next.js version) for provenance.
"""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
from datetime import UTC, datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FRONTEND = ROOT / "frontend"
COPY = ["package.json", "package-lock.json", ".npmrc", "tsconfig.json", "src", "public"]
NEXT_CONFIG = """import type { NextConfig } from "next";

// GENERATED by deploy/zerogpu/build_frontend.py: static export for the ZeroGPU Space (same-origin /api via FastAPI).
const config: NextConfig = {
  output: "export",
  reactStrictMode: true,
  poweredByHeader: false,
};

export default config;
"""


def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "deploy/zerogpu/web"))
    ap.add_argument("--npm-ci", action="store_true", help="install packages with npm ci instead of copying frontend/node_modules")
    a = ap.parse_args()
    out = Path(a.out).resolve()
    with tempfile.TemporaryDirectory(prefix="pdeflow-export-") as tmp:
        work = Path(tmp) / "frontend"
        work.mkdir()
        for name in COPY:
            src = FRONTEND / name
            (shutil.copytree if src.is_dir() else shutil.copy2)(src, work / name)
        shutil.rmtree(work / "src/app/api")
        (work / "next.config.ts").write_text(NEXT_CONFIG)
        if a.npm_ci or not (FRONTEND / "node_modules").is_dir():
            subprocess.run(["npm", "ci", "--no-audit", "--no-fund"], cwd=work, check=True)
        else:  # a real copy: Turbopack does not follow a node_modules symlink outside the project root
            shutil.copytree(FRONTEND / "node_modules", work / "node_modules", symlinks=True)
        env = {**os.environ, "NEXT_TELEMETRY_DISABLED": "1"}
        subprocess.run(["npx", "next", "build"], cwd=work, env=env, check=True)
        if out.exists():
            shutil.rmtree(out)
        shutil.copytree(work / "out", out)
        next_version = json.loads((work / "node_modules/next/package.json").read_text())["version"]
    dirty = bool(git("status", "--porcelain", "--", "frontend"))
    info = {"built_utc": datetime.now(UTC).isoformat(timespec="seconds"), "git_commit": git("rev-parse", "HEAD"),
            "frontend_tree": git("rev-parse", "HEAD:frontend"), "frontend_dirty": dirty, "next": next_version,
            "mode": "static export (src/app/api removed; same-origin /api served by FastAPI)"}
    (out / "build-info.json").write_text(json.dumps(info, indent=2))
    pages = sorted(p.name for p in out.glob("*.html"))
    print(f"static export written to {out}: {pages}; {sum(f.stat().st_size for f in out.rglob('*') if f.is_file()) / 1e6:.1f} MB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
